    CONSTRAINT fk_conversation_user_state_conversation
        FOREIGN KEY (conversation_id) REFERENCES conversations (conversation_id) ON DELETE CASCADE,
    CONSTRAINT fk_conversation_user_state_user
        FOREIGN KEY (user_id) REFERENCES users (user_id),
    CONSTRAINT fk_conversation_user_state_last_read
        FOREIGN KEY (conversation_id, last_read_message_id)
        REFERENCES messages (conversation_id, message_id),
    CONSTRAINT ck_conversation_user_state_read_time CHECK (
        (last_read_message_id IS NULL AND last_read_at IS NULL)
        OR (last_read_message_id IS NOT NULL AND last_read_at IS NOT NULL)
    )
);

