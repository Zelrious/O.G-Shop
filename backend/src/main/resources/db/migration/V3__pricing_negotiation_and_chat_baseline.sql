        FOREIGN KEY (fee_policy_id) REFERENCES system_fee_policies (fee_policy_id),
    ADD CONSTRAINT ck_offers_item_price CHECK (offered_item_price > 0),
    ADD CONSTRAINT ck_offers_fees CHECK (
        buyer_system_fee >= 0
        AND seller_system_fee >= 0
        AND seller_system_fee <= offered_item_price
        AND buyer_subtotal = offered_item_price + buyer_system_fee
        AND seller_proceeds = offered_item_price - seller_system_fee
    ),
    ADD CONSTRAINT ck_offers_currency CHECK (currency = 'VND'),
    ADD CONSTRAINT ck_offers_status CHECK (
        status IN ('PENDING', 'ACCEPTED', 'REJECTED', 'COUNTERED', 'WITHDRAWN', 'EXPIRED')
    ),
    ADD CONSTRAINT ck_offers_response CHECK (
        (status = 'PENDING' AND responded_at IS NULL AND responded_by IS NULL)
        OR
        (status = 'EXPIRED' AND responded_at IS NOT NULL AND responded_by IS NULL)
        OR
        (status = 'WITHDRAWN' AND responded_at IS NOT NULL AND responded_by = proposer_id)
        OR
        (
            status IN ('ACCEPTED', 'REJECTED', 'COUNTERED')
            AND responded_at IS NOT NULL
            AND responded_by IS NOT NULL
            AND responded_by <> proposer_id
        )
    ),
    ADD CONSTRAINT ck_offers_expiry CHECK (expires_at IS NULL OR expires_at > created_at),
    ADD CONSTRAINT ck_offers_not_self_parent CHECK (
        parent_offer_id IS NULL OR parent_offer_id <> offer_id
    );

