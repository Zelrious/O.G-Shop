ALTER TABLE offers
    ADD COLUMN conversation_id BIGINT,
    ADD COLUMN proposer_id BIGINT,
    ADD COLUMN responded_by BIGINT,
    ADD COLUMN parent_offer_id BIGINT,
    ADD COLUMN fee_policy_id BIGINT,
    ADD COLUMN buyer_system_fee NUMERIC(19,2),
    ADD COLUMN seller_system_fee NUMERIC(19,2),
    ADD COLUMN buyer_subtotal NUMERIC(19,2),
    ADD COLUMN seller_proceeds NUMERIC(19,2),
    ADD COLUMN currency CHAR(3),
    ADD COLUMN version BIGINT NOT NULL DEFAULT 0;

UPDATE offers AS offer
SET conversation_id = conversation.conversation_id,
    proposer_id = offer.buyer_id,
    responded_by = CASE
        WHEN offer.status IN ('ACCEPTED', 'REJECTED', 'COUNTERED') THEN offer.seller_id
        ELSE NULL
    END,
    fee_policy_id = (
        SELECT policy.fee_policy_id
        FROM system_fee_policies AS policy
        WHERE policy.policy_code = 'DEFAULT_ZERO_V1'
    ),
    buyer_system_fee = 0,
    seller_system_fee = 0,
    buyer_subtotal = offer.offered_item_price,
    seller_proceeds = offer.offered_item_price,
    currency = product.currency
FROM conversations AS conversation
JOIN products AS product ON product.product_id = conversation.product_id
WHERE conversation.buyer_id = offer.buyer_id
  AND conversation.seller_id = offer.seller_id
  AND conversation.product_id = offer.product_id;

