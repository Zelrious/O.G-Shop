-- Pricing, negotiation, chat-read model and transactional event baseline.
-- PostgreSQL remains the source of truth; Redis/WebSocket consumers are fed
-- from the outbox after the owning transaction commits.

-- ---------------------------------------------------------------------------
-- 1. Versioned system-fee policy and explicit seller-listed price
-- ---------------------------------------------------------------------------

CREATE TABLE system_fee_policies (
    fee_policy_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    policy_code            VARCHAR(50) NOT NULL,
    policy_name            VARCHAR(120) NOT NULL,
    buyer_fee_rate         NUMERIC(9,6) NOT NULL DEFAULT 0,
    buyer_fixed_fee        NUMERIC(19,2) NOT NULL DEFAULT 0,
    seller_fee_rate        NUMERIC(9,6) NOT NULL DEFAULT 0,
    seller_fixed_fee       NUMERIC(19,2) NOT NULL DEFAULT 0,
    minimum_buyer_fee      NUMERIC(19,2),
    maximum_buyer_fee      NUMERIC(19,2),
    minimum_seller_fee     NUMERIC(19,2),
    maximum_seller_fee     NUMERIC(19,2),
    rounding_scale         SMALLINT NOT NULL DEFAULT 0,
    rounding_mode          VARCHAR(20) NOT NULL DEFAULT 'HALF_UP',
    currency               CHAR(3) NOT NULL DEFAULT 'VND',
    status                 VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    version                INTEGER NOT NULL,
    effective_from         TIMESTAMPTZ NOT NULL,
    effective_to           TIMESTAMPTZ,
    created_at             TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by             BIGINT,

    CONSTRAINT uq_system_fee_policies_code UNIQUE (policy_code),
    CONSTRAINT uq_system_fee_policies_version UNIQUE (version),
    CONSTRAINT fk_system_fee_policies_created_by FOREIGN KEY (created_by) REFERENCES users (user_id),
    CONSTRAINT ck_system_fee_policies_rates CHECK (
        buyer_fee_rate BETWEEN 0 AND 1 AND seller_fee_rate BETWEEN 0 AND 1
    ),
    CONSTRAINT ck_system_fee_policies_fixed_fees CHECK (
        buyer_fixed_fee >= 0 AND seller_fixed_fee >= 0
    ),
    CONSTRAINT ck_system_fee_policies_buyer_bounds CHECK (
        (minimum_buyer_fee IS NULL OR minimum_buyer_fee >= 0)
        AND (maximum_buyer_fee IS NULL OR maximum_buyer_fee >= 0)
        AND (
            minimum_buyer_fee IS NULL
            OR maximum_buyer_fee IS NULL
            OR minimum_buyer_fee <= maximum_buyer_fee
        )
    ),
    CONSTRAINT ck_system_fee_policies_seller_bounds CHECK (
        (minimum_seller_fee IS NULL OR minimum_seller_fee >= 0)
        AND (maximum_seller_fee IS NULL OR maximum_seller_fee >= 0)
        AND (
            minimum_seller_fee IS NULL
            OR maximum_seller_fee IS NULL
            OR minimum_seller_fee <= maximum_seller_fee
        )
    ),
    CONSTRAINT ck_system_fee_policies_rounding CHECK (
        rounding_scale BETWEEN 0 AND 2 AND rounding_mode IN ('HALF_UP', 'HALF_EVEN', 'DOWN', 'UP')
    ),
    CONSTRAINT ck_system_fee_policies_currency CHECK (currency = 'VND'),
    CONSTRAINT ck_system_fee_policies_status CHECK (status IN ('DRAFT', 'ACTIVE', 'RETIRED')),
    CONSTRAINT ck_system_fee_policies_version CHECK (version > 0),
    CONSTRAINT ck_system_fee_policies_effective_window CHECK (
        effective_to IS NULL OR effective_to > effective_from
    )
);

CREATE UNIQUE INDEX uq_system_fee_policies_one_active
    ON system_fee_policies (status)
    WHERE status = 'ACTIVE';

