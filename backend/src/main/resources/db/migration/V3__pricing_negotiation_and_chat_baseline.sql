-- ---------------------------------------------------------------------------
-- 6. Durable event publication boundary for Redis/WebSocket/notifications
-- ---------------------------------------------------------------------------

CREATE TABLE outbox_events (
    event_id        UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    aggregate_type  VARCHAR(80) NOT NULL,
    aggregate_id    VARCHAR(100) NOT NULL,
    event_type      VARCHAR(120) NOT NULL,
    payload         JSONB NOT NULL,
    occurred_at     TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    available_at    TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    published_at    TIMESTAMPTZ,
    attempt_count   INTEGER NOT NULL DEFAULT 0,
    last_error      VARCHAR(1000),

    CONSTRAINT ck_outbox_events_payload CHECK (jsonb_typeof(payload) = 'object'),
    CONSTRAINT ck_outbox_events_attempt_count CHECK (attempt_count >= 0),
    CONSTRAINT ck_outbox_events_publish_time CHECK (
        published_at IS NULL OR published_at >= occurred_at
    )
);

CREATE INDEX ix_outbox_events_unpublished
    ON outbox_events (available_at, occurred_at, event_id)
    WHERE published_at IS NULL;
CREATE INDEX ix_outbox_events_aggregate
    ON outbox_events (aggregate_type, aggregate_id, occurred_at DESC);
