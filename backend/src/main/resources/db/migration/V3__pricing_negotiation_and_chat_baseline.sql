-- 2. Conversation product snapshot and stable inbox ordering
-- ---------------------------------------------------------------------------

ALTER TABLE conversations
    ADD COLUMN product_title_snapshot VARCHAR(200),
    ADD COLUMN product_price_at_start NUMERIC(19,2),
    ADD COLUMN product_thumbnail_snapshot TEXT,
    ADD COLUMN currency CHAR(3),
    ADD COLUMN last_message_id BIGINT,
    ADD COLUMN last_activity_at TIMESTAMPTZ,
    ADD COLUMN status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    ADD COLUMN closed_at TIMESTAMPTZ;

UPDATE conversations AS conversation
SET product_title_snapshot = product.title,
    product_price_at_start = product.listed_price,
    product_thumbnail_snapshot = (
        SELECT media.media_url
        FROM product_media AS media
        WHERE media.product_id = product.product_id
          AND media.media_type = 'IMAGE'
        ORDER BY media.display_order, media.media_id
        LIMIT 1
    ),
    currency = product.currency,
    last_activity_at = COALESCE(conversation.last_message_at, conversation.created_at)
FROM products AS product
WHERE product.product_id = conversation.product_id;

-- V1 offers did not reference conversations. Preserve them by creating the
-- missing buyer/seller/product conversation before the offer columns change.
INSERT INTO conversations (
    buyer_id,
    seller_id,
    product_id,
    created_at,
    product_title_snapshot,
    product_price_at_start,
    product_thumbnail_snapshot,
    currency,
    last_activity_at
)
SELECT
    legacy_offer.buyer_id,
    legacy_offer.seller_id,
    legacy_offer.product_id,
    MIN(legacy_offer.created_at),
    product.title,
    product.listed_price,
    (
        SELECT media.media_url
        FROM product_media AS media
        WHERE media.product_id = product.product_id
          AND media.media_type = 'IMAGE'
        ORDER BY media.display_order, media.media_id
        LIMIT 1
    ),
    product.currency,
    MAX(legacy_offer.created_at)
FROM offers AS legacy_offer
JOIN products AS product ON product.product_id = legacy_offer.product_id
GROUP BY
    legacy_offer.buyer_id,
    legacy_offer.seller_id,
    legacy_offer.product_id,
    product.product_id,
    product.title,
    product.listed_price,
    product.currency
ON CONFLICT (buyer_id, seller_id, product_id) DO NOTHING;

UPDATE conversations AS conversation
SET last_message_id = (
        SELECT message.message_id
        FROM messages AS message
        WHERE message.conversation_id = conversation.conversation_id
        ORDER BY message.created_at DESC, message.message_id DESC
        LIMIT 1
    );

