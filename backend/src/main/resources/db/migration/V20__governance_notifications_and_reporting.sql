CREATE TABLE account_status_events (
    event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(user_id),
    old_status VARCHAR(20),
    new_status VARCHAR(20) NOT NULL,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE FUNCTION og_record_account_status() RETURNS TRIGGER
LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
BEGIN
    IF TG_OP='INSERT' OR NEW.status IS DISTINCT FROM OLD.status THEN
        INSERT INTO account_status_events(user_id,old_status,new_status)
            VALUES(NEW.user_id,CASE WHEN TG_OP='UPDATE' THEN OLD.status ELSE NULL END,NEW.status);
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER trg_account_status_event AFTER INSERT OR UPDATE OF status ON users
    FOR EACH ROW EXECUTE FUNCTION og_record_account_status();
CREATE TRIGGER trg_account_status_history BEFORE UPDATE OR DELETE ON account_status_events
    FOR EACH ROW EXECUTE FUNCTION og_reject_history_mutation();
COMMENT ON TABLE account_status_events IS 'History starts at V20. Do not fabricate activity before migration.';

