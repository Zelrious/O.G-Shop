CREATE TABLE penalty_ledger (
    entry_id UUID PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(user_id),
    report_id BIGINT REFERENCES reports(report_id),
    policy_id BIGINT NOT NULL REFERENCES penalty_policies(policy_id),
    points_delta INTEGER NOT NULL CHECK(points_delta<>0),
    adjustment_of UUID REFERENCES penalty_ledger(entry_id),
    decided_by BIGINT NOT NULL REFERENCES users(user_id),
    reason TEXT NOT NULL CHECK(btrim(reason)<>''),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    command_key VARCHAR(150) NOT NULL UNIQUE,
    CHECK((points_delta>0 AND report_id IS NOT NULL) OR (points_delta<0 AND adjustment_of IS NOT NULL))
);
CREATE UNIQUE INDEX uq_penalty_report_user ON penalty_ledger(report_id,user_id) WHERE adjustment_of IS NULL;
CREATE FUNCTION og_guard_penalty_entry() RETURNS TRIGGER
LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
DECLARE points BIGINT;
BEGIN
    PERFORM 1 FROM users WHERE user_id=NEW.user_id FOR UPDATE;
    SELECT COALESCE(sum(points_delta),0) INTO points FROM penalty_ledger WHERE user_id=NEW.user_id;
    IF NOT og_has_role(NEW.decided_by,'KTV') OR points+NEW.points_delta<0
        OR (NEW.points_delta>0 AND NOT EXISTS(SELECT 1 FROM reports
            WHERE report_id=NEW.report_id AND status='RESOLVED'))
        OR (NEW.adjustment_of IS NOT NULL AND NOT EXISTS(SELECT 1 FROM penalty_ledger
            WHERE entry_id=NEW.adjustment_of AND user_id=NEW.user_id)) THEN
        RAISE EXCEPTION 'Penalty requires confirmed KTV violation/correction' USING ERRCODE='23514';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER trg_penalty_entry_guard BEFORE INSERT ON penalty_ledger
    FOR EACH ROW EXECUTE FUNCTION og_guard_penalty_entry();
CREATE TRIGGER trg_penalty_entry_history BEFORE UPDATE OR DELETE ON penalty_ledger
    FOR EACH ROW EXECUTE FUNCTION og_reject_history_mutation();

CREATE TABLE review_revisions (
    revision_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    review_id BIGINT NOT NULL REFERENCES reviews(review_id),
    original_record JSONB NOT NULL CHECK(jsonb_typeof(original_record)='object'),
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE FUNCTION og_guard_review_parties() RETURNS TRIGGER
LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
DECLARE o orders;
BEGIN
    SELECT * INTO STRICT o FROM orders WHERE order_id=NEW.order_id;
    IF NOT ((NEW.reviewer_id=o.buyer_id AND NEW.reviewee_id=o.seller_id)
        OR (NEW.reviewer_id=o.seller_id AND NEW.reviewee_id=o.buyer_id))
        OR (o.workflow_model='UC83' AND o.valid_delivered_at IS NULL)
        OR (o.workflow_model='LEGACY_V14' AND o.status NOT IN ('DELIVERED','COMPLETED')) THEN
        RAISE EXCEPTION 'Review requires delivered order and its two parties' USING ERRCODE='23514';
    END IF;
    IF TG_OP='UPDATE' THEN
        IF ROW(NEW.order_id,NEW.reviewer_id,NEW.reviewee_id) IS DISTINCT FROM ROW(OLD.order_id,OLD.reviewer_id,OLD.reviewee_id) THEN
            RAISE EXCEPTION 'Review identity immutable' USING ERRCODE='23514';
        END IF;
        INSERT INTO review_revisions(review_id,original_record) VALUES(OLD.review_id,to_jsonb(OLD));
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER trg_review_party_guard BEFORE INSERT OR UPDATE ON reviews
    FOR EACH ROW EXECUTE FUNCTION og_guard_review_parties();
