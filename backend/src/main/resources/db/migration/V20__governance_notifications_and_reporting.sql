CREATE FUNCTION og_guard_manual_recipient() RETURNS TRIGGER
LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
DECLARE d notification_dispatches;
BEGIN
    IF NEW.dispatch_id IS NOT NULL THEN
        SELECT * INTO STRICT d FROM notification_dispatches WHERE dispatch_id=NEW.dispatch_id;
        IF NOT (og_has_role(NEW.user_id,'BUYER') OR og_has_role(NEW.user_id,'SELLER') OR og_has_role(NEW.user_id,'KTV')) THEN
            RAISE EXCEPTION 'Manual recipient must be Buyer/Seller/KTV' USING ERRCODE='23514';
        END IF;
        NEW.sender_id:=d.sender_id; NEW.event_id:=d.event_id; NEW.title:=d.title; NEW.content:=d.content;
        NEW.target_data:=d.target_data;
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER trg_manual_recipient_guard BEFORE INSERT ON notifications
    FOR EACH ROW EXECUTE FUNCTION og_guard_manual_recipient();
