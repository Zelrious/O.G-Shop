CREATE TABLE account_restrictions (
    restriction_id UUID PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(user_id),
    scope VARCHAR(25) NOT NULL CHECK(scope IN ('NEW_TRANSACTIONS','LOGIN')),
    imposed_by BIGINT NOT NULL REFERENCES users(user_id),
    reason TEXT NOT NULL CHECK(btrim(reason)<>''),
    source_key VARCHAR(150) NOT NULL,
    opened_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    closed_at TIMESTAMPTZ,
    UNIQUE(user_id,source_key),
    CHECK(closed_at IS NULL OR closed_at>=opened_at)
);
CREATE INDEX ix_account_restrictions_open ON account_restrictions(user_id,scope) WHERE closed_at IS NULL;
CREATE FUNCTION og_guard_account_restriction() RETURNS TRIGGER
LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
BEGIN
    PERFORM 1 FROM users WHERE user_id=NEW.user_id FOR UPDATE;
    IF NOT (og_has_role(NEW.imposed_by,'KTV') OR og_has_role(NEW.imposed_by,'ADMIN')) THEN
        RAISE EXCEPTION 'Restriction needs KTV/Admin authority' USING ERRCODE='23514';
    END IF;
    IF NEW.scope='LOGIN' AND NEW.closed_at IS NULL AND (
        EXISTS(SELECT 1 FROM orders o WHERE NEW.user_id IN (o.buyer_id,o.seller_id)
            AND o.status NOT IN ('COMPLETED','CANCELLED','REFUNDED'))
        OR EXISTS(SELECT 1 FROM cases c LEFT JOIN orders o USING(order_id)
            WHERE c.state NOT IN ('CLOSED','REJECTED')
                AND NEW.user_id IN (c.created_by,o.buyer_id,o.seller_id))) THEN
        RAISE EXCEPTION 'Open obligations require login access; restrict new transactions instead' USING ERRCODE='23514';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER trg_account_restriction_guard BEFORE INSERT OR UPDATE ON account_restrictions
    FOR EACH ROW EXECUTE FUNCTION og_guard_account_restriction();
