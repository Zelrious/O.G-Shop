CREATE VIEW completed_case_statistics AS
    SELECT c.case_id,c.case_type,c.order_id,c.closed_at,d.outcome,d.goods_refund_amount
    FROM cases c LEFT JOIN LATERAL(
        SELECT decision.outcome,decision.goods_refund_amount FROM case_decisions decision
        JOIN case_rounds round USING(round_id) WHERE round.case_id=c.case_id AND decision.is_final
        ORDER BY decision.decided_at DESC,decision.decision_id DESC LIMIT 1
    ) d ON TRUE WHERE c.state IN ('CLOSED','REJECTED');
CREATE VIEW reputation_summary AS
    SELECT u.user_id,COALESCE(r.average_stars,0) AS average_stars,COALESCE(r.review_count,0) AS review_count,
        COALESCE(p.penalty_points,0) AS penalty_points,
        CASE WHEN r.review_count IS NULL THEN NULL ELSE r.average_stars-COALESCE(p.penalty_points,0) END AS reputation
    FROM users u LEFT JOIN (
        SELECT reviewee_id,avg(rating) AS average_stars,count(*) AS review_count
        FROM reviews rv JOIN orders o USING(order_id) WHERE rv.deleted_at IS NULL
          AND ((rv.reviewer_id=o.buyer_id AND rv.reviewee_id=o.seller_id) OR
               (rv.reviewer_id=o.seller_id AND rv.reviewee_id=o.buyer_id))
          AND ((o.workflow_model='UC83' AND o.valid_delivered_at IS NOT NULL) OR
               (o.workflow_model='LEGACY_V14' AND o.status IN ('DELIVERED','COMPLETED')))
          GROUP BY reviewee_id
    ) r ON r.reviewee_id=u.user_id LEFT JOIN (
        SELECT user_id,sum(points_delta) AS penalty_points FROM penalty_ledger GROUP BY user_id
    ) p ON p.user_id=u.user_id;
CREATE VIEW uc83_public_products AS
    SELECT p.* FROM products p JOIN users seller ON seller.user_id=p.seller_id
    WHERE p.workflow_model='UC83' AND p.status='ACTIVE' AND p.deleted_at IS NULL AND p.quantity_available>0
      AND seller.status='ACTIVE' AND NOT EXISTS(SELECT 1 FROM account_restrictions ar
        WHERE ar.user_id=p.seller_id AND ar.closed_at IS NULL);

CREATE FUNCTION og_guard_new_transaction() RETURNS TRIGGER
LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
DECLARE o orders;
BEGIN
    SELECT o1.* INTO STRICT o FROM order_items i JOIN orders o1 USING(order_id) WHERE i.order_item_id=NEW.order_item_id;
    PERFORM 1 FROM users WHERE user_id IN (o.buyer_id,o.seller_id) ORDER BY user_id FOR UPDATE;
    IF NOT og_has_role(o.buyer_id,'BUYER') OR NOT og_has_role(o.seller_id,'SELLER')
        OR EXISTS(SELECT 1 FROM account_restrictions WHERE user_id IN (o.buyer_id,o.seller_id) AND closed_at IS NULL)
        OR EXISTS(SELECT 1 FROM seller_buyer_blocks WHERE seller_id=o.seller_id AND buyer_id=o.buyer_id AND unblocked_at IS NULL)
        OR NOT EXISTS(SELECT 1 FROM seller_profiles s JOIN ekyc_profiles e ON e.profile_id=s.ekyc_profile_id
            JOIN ekyc_decisions d ON d.profile_id=e.profile_id WHERE s.user_id=o.seller_id AND s.state='APPROVED'
                AND e.state='VERIFIED' AND d.outcome='VERIFIED' AND e.reference_expires_at>clock_timestamp())
        OR EXISTS(SELECT 1 FROM ekyc_profiles WHERE user_id=o.seller_id AND state IN ('DRAFT','IN_PROGRESS','PENDING')) THEN
        RAISE EXCEPTION 'New transaction blocked by identity/restriction/party block' USING ERRCODE='23514'; END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER trg_new_transaction_guard BEFORE INSERT ON inventory_reservations
    FOR EACH ROW EXECUTE FUNCTION og_guard_new_transaction();
