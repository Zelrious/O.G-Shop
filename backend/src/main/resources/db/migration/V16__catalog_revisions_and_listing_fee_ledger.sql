CREATE FUNCTION og_compute_listing_assessment() RETURNS TRIGGER
LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
DECLARE r product_revisions; f listing_fee_policies;
BEGIN
    PERFORM 1 FROM products WHERE product_id=NEW.product_id FOR UPDATE;
    SELECT * INTO STRICT r FROM product_revisions WHERE revision_id=NEW.revision_id;
    IF r.state<>'SUBMITTED' OR r.provenance<>'UC83' OR NOT EXISTS (
        SELECT 1 FROM product_moderation_decisions WHERE decision_id=NEW.decision_id
            AND revision_id=r.revision_id AND decision='APPROVED') THEN
        RAISE EXCEPTION 'Fee requires approval of this revision' USING ERRCODE='23514';
    END IF;
    IF EXISTS(SELECT 1 FROM listing_fee_charges c JOIN listing_fee_assessments a USING(assessment_id)
              WHERE a.product_id=NEW.product_id AND c.state IN ('PENDING','RECONCILIATION')) THEN
        RAISE EXCEPTION 'Listing has an unresolved fee charge' USING ERRCODE='23514';
    END IF;
    NEW.assessed_at := clock_timestamp();
    SELECT * INTO STRICT f FROM listing_fee_policies WHERE policy_id=NEW.policy_id
        AND effective_from<=NEW.assessed_at AND (effective_until IS NULL OR effective_until>NEW.assessed_at);
    NEW.listed_total := r.listed_unit_price*r.quantity;
    SELECT listed_total INTO NEW.previous_approved_total FROM listing_fee_assessments
        WHERE product_id=NEW.product_id ORDER BY assessment_id DESC LIMIT 1;
    SELECT COALESCE(sum(receipt.amount),0) INTO NEW.cumulative_before FROM listing_fee_receipts receipt
        JOIN listing_fee_charges c USING(charge_id) JOIN listing_fee_assessments a USING(assessment_id)
        WHERE a.product_id=NEW.product_id;
    NEW.computed_fee := CASE WHEN NEW.listed_total<f.threshold_amount THEN f.fixed_below
        ELSE round(NEW.listed_total*f.rate_at_or_above,0) END;
    NEW.amount_due := CASE WHEN NEW.previous_approved_total IS NULL
        OR NEW.listed_total>NEW.previous_approved_total
        THEN greatest(0,NEW.computed_fee-NEW.cumulative_before) ELSE 0 END;
    RETURN NEW;
END;
$$;
