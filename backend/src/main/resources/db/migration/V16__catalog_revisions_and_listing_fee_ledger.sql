CREATE FUNCTION og_guard_revision_media() RETURNS TRIGGER
LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
DECLARE parent product_revisions; n INTEGER;
BEGIN
    IF TG_OP<>'INSERT' THEN
        SELECT * INTO STRICT parent FROM product_revisions WHERE revision_id=OLD.revision_id FOR UPDATE;
        IF parent.state<>'DRAFT' THEN
            RAISE EXCEPTION 'Submitted revision media is immutable' USING ERRCODE='23514';
        END IF;
        IF TG_OP='DELETE' THEN RETURN OLD; END IF;
        IF NEW.revision_id<>OLD.revision_id THEN
            RAISE EXCEPTION 'Cannot move media between revisions' USING ERRCODE='23514';
        END IF;
    ELSE
        SELECT * INTO STRICT parent FROM product_revisions WHERE revision_id=NEW.revision_id FOR UPDATE;
    END IF;
    IF parent.state<>'DRAFT' OR parent.provenance<>'UC83' THEN
        RAISE EXCEPTION 'Only current draft accepts media' USING ERRCODE='23514';
    END IF;
    SELECT count(*) INTO n FROM revision_media WHERE revision_id=NEW.revision_id
        AND media_type=NEW.media_type AND revision_media_id IS DISTINCT FROM NEW.revision_media_id;
    IF n >= (CASE NEW.media_type WHEN 'IMAGE' THEN 5 ELSE 2 END) THEN
        RAISE EXCEPTION 'Revision media count exceeded' USING ERRCODE='23514';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER trg_revision_media_guard BEFORE INSERT OR UPDATE OR DELETE ON revision_media
    FOR EACH ROW EXECUTE FUNCTION og_guard_revision_media();

