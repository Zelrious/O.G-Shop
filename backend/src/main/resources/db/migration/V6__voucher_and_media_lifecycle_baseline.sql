-- ---------------------------------------------------------------------------
-- 1. Voucher Engine & Order Discount Invariants
-- ---------------------------------------------------------------------------

CREATE TABLE vouchers (
    voucher_id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                   VARCHAR(50) NOT NULL,
    title                  VARCHAR(200) NOT NULL,
    description            TEXT,
    voucher_type           VARCHAR(30) NOT NULL,
    discount_type          VARCHAR(20) NOT NULL,
    discount_value         NUMERIC(19,2) NOT NULL,
    max_discount_amount    NUMERIC(19,2),
    min_order_amount       NUMERIC(19,2) NOT NULL DEFAULT 0,
    sponsor_type           VARCHAR(20) NOT NULL DEFAULT 'PLATFORM',
    seller_id              BIGINT,
    total_usage_limit      INTEGER,
    current_usage_count    INTEGER NOT NULL DEFAULT 0,
    max_usage_per_user     INTEGER NOT NULL DEFAULT 1,
    start_time             TIMESTAMPTZ NOT NULL,
    end_time               TIMESTAMPTZ NOT NULL,
    is_active              BOOLEAN NOT NULL DEFAULT TRUE,
    version                BIGINT NOT NULL DEFAULT 0,
    created_at             TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at             TIMESTAMPTZ,

    CONSTRAINT uq_vouchers_code UNIQUE (code),
    CONSTRAINT fk_vouchers_seller FOREIGN KEY (seller_id) REFERENCES users (user_id),
    CONSTRAINT ck_vouchers_code_format CHECK (code = upper(btrim(code))),
    CONSTRAINT ck_vouchers_type CHECK (voucher_type IN ('ORDER_DISCOUNT', 'SHIPPING_DISCOUNT', 'BUYER_FEE_DISCOUNT')),
    CONSTRAINT ck_vouchers_discount_type CHECK (discount_type IN ('FIXED_AMOUNT', 'PERCENTAGE')),
    CONSTRAINT ck_vouchers_discount_value CHECK (
        (discount_type = 'FIXED_AMOUNT' AND discount_value > 0)
        OR
        (discount_type = 'PERCENTAGE' AND discount_value > 0 AND discount_value <= 100)
    ),
    CONSTRAINT ck_vouchers_sponsor CHECK (
        (sponsor_type = 'PLATFORM' AND seller_id IS NULL)
        OR
        (sponsor_type = 'SELLER' AND seller_id IS NOT NULL)
    ),
    CONSTRAINT ck_vouchers_usage CHECK (
        current_usage_count >= 0
        AND (total_usage_limit IS NULL OR current_usage_count <= total_usage_limit)
        AND max_usage_per_user > 0
    ),
    CONSTRAINT ck_vouchers_window CHECK (end_time > start_time)
);

CREATE INDEX ix_vouchers_active_window ON vouchers (is_active, start_time, end_time);
CREATE INDEX ix_vouchers_seller ON vouchers (seller_id) WHERE seller_id IS NOT NULL;

CREATE TABLE order_vouchers (
    order_voucher_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id               BIGINT NOT NULL,
    voucher_id             BIGINT NOT NULL,
    voucher_code_snapshot  VARCHAR(50) NOT NULL,
    voucher_type_snapshot  VARCHAR(30) NOT NULL,
    sponsor_type_snapshot  VARCHAR(20) NOT NULL,
    discount_amount        NUMERIC(19,2) NOT NULL,
    applied_at             TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_order_vouchers_order FOREIGN KEY (order_id) REFERENCES orders (order_id),
    CONSTRAINT fk_order_vouchers_voucher FOREIGN KEY (voucher_id) REFERENCES vouchers (voucher_id),
    CONSTRAINT uq_order_vouchers_order_voucher UNIQUE (order_id, voucher_id),
    CONSTRAINT ck_order_vouchers_discount CHECK (discount_amount > 0)
);

CREATE INDEX ix_order_vouchers_order ON order_vouchers (order_id);
CREATE INDEX ix_order_vouchers_voucher ON order_vouchers (voucher_id);

ALTER TABLE orders
    ADD COLUMN voucher_discount_amount NUMERIC(19,2) NOT NULL DEFAULT 0,
    ADD COLUMN shipping_discount_amount NUMERIC(19,2) NOT NULL DEFAULT 0,
    ADD COLUMN sponsor_type VARCHAR(20) NOT NULL DEFAULT 'PLATFORM';

ALTER TABLE orders DROP CONSTRAINT ck_orders_amounts;

ALTER TABLE orders ADD CONSTRAINT ck_orders_amounts CHECK (
    subtotal > 0
    AND buyer_system_fee >= 0
    AND seller_system_fee >= 0
    AND seller_system_fee <= subtotal
    AND shipping_fee >= 0
    AND voucher_discount_amount >= 0
    AND shipping_discount_amount >= 0
    AND shipping_discount_amount <= shipping_fee
    AND (voucher_discount_amount + shipping_discount_amount) < (subtotal + buyer_system_fee + shipping_fee)
    AND seller_proceeds = (
        subtotal 
        - (CASE WHEN sponsor_type = 'SELLER' THEN voucher_discount_amount ELSE 0 END)
        - seller_system_fee
    )
    AND total_amount = subtotal + buyer_system_fee + shipping_fee - voucher_discount_amount - shipping_discount_amount
);

