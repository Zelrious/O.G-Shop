CREATE TABLE order_unboxing_evidences (
    evidence_id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id               BIGINT NOT NULL UNIQUE,
    buyer_id               BIGINT NOT NULL,
    status                 VARCHAR(30) NOT NULL DEFAULT 'PENDING',
    video_url              TEXT,
    thumbnail_url          TEXT,
    cloudinary_public_id   VARCHAR(255),
    video_duration_sec     INTEGER,
    file_size_bytes        BIGINT,
    recorded_at            TIMESTAMPTZ,
    skipped_at             TIMESTAMPTZ,
    created_at             TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_unboxing_order FOREIGN KEY (order_id) REFERENCES orders (order_id),
    CONSTRAINT fk_unboxing_buyer FOREIGN KEY (buyer_id) REFERENCES users (user_id),
    CONSTRAINT ck_unboxing_status CHECK (status IN ('PENDING', 'SUBMITTED', 'SKIPPED_BY_BUYER')),
    CONSTRAINT ck_unboxing_video_duration CHECK (video_duration_sec IS NULL OR (video_duration_sec > 0 AND video_duration_sec <= 180)),
    CONSTRAINT ck_unboxing_file_size CHECK (file_size_bytes IS NULL OR (file_size_bytes > 0 AND file_size_bytes <= 104857600)),
    CONSTRAINT ck_unboxing_state_data CHECK (
        (status = 'PENDING' AND video_url IS NULL AND recorded_at IS NULL AND skipped_at IS NULL)
        OR
        (status = 'SUBMITTED' AND video_url IS NOT NULL AND recorded_at IS NOT NULL AND skipped_at IS NULL)
        OR
        (status = 'SKIPPED_BY_BUYER' AND video_url IS NULL AND skipped_at IS NOT NULL)
    )
);

CREATE INDEX ix_unboxing_order_status ON order_unboxing_evidences (order_id, status);

