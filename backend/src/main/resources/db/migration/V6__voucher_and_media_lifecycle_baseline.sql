    file_size_bytes IS NULL OR (file_size_bytes > 0 AND file_size_bytes <= 52428800) -- 50 MB
);

-- Prevent exceeding maximum 5 images and 1 video per product
CREATE OR REPLACE FUNCTION fn_enforce_product_media_limits()
RETURNS TRIGGER AS $$
DECLARE
    v_image_count INTEGER;
    v_video_count INTEGER;
BEGIN
    SELECT COUNT(*) FILTER (WHERE media_type = 'IMAGE'),
           COUNT(*) FILTER (WHERE media_type = 'VIDEO')
    INTO v_image_count, v_video_count
    FROM product_media
    WHERE product_id = NEW.product_id;

    IF NEW.media_type = 'IMAGE' AND v_image_count >= 5 THEN
        RAISE EXCEPTION 'Mỗi sản phẩm chỉ được đăng tối đa 5 hình ảnh.';
    END IF;

    IF NEW.media_type = 'VIDEO' AND v_video_count >= 1 THEN
        RAISE EXCEPTION 'Mỗi sản phẩm chỉ được đăng tối đa 1 video cận cảnh.';
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_check_product_media_limits
BEFORE INSERT ON product_media
FOR EACH ROW
EXECUTE FUNCTION fn_enforce_product_media_limits();

-- Strict publication guard: must have >= 1 image AND >= 1 video to be ACTIVE or PENDING
CREATE OR REPLACE FUNCTION fn_check_product_media_requirements()
RETURNS TRIGGER AS $$
DECLARE
    v_image_count INTEGER;
    v_video_count INTEGER;
BEGIN
    IF NEW.status IN ('PENDING', 'ACTIVE') AND (OLD.status IS NULL OR OLD.status = 'DRAFT') THEN
        SELECT COUNT(*) FILTER (WHERE media_type = 'IMAGE'),
               COUNT(*) FILTER (WHERE media_type = 'VIDEO')
        INTO v_image_count, v_video_count
        FROM product_media
        WHERE product_id = NEW.product_id;

        IF v_image_count < 1 THEN
            RAISE EXCEPTION 'Tin đăng phải có ít nhất 1 hình ảnh sản phẩm (media_type=IMAGE).';
        END IF;

        IF v_video_count < 1 THEN
            RAISE EXCEPTION 'Tin đăng đồ cũ phải có ít nhất 1 video quay cận cảnh sản phẩm (media_type=VIDEO).';
        END IF;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_check_product_media_publish
BEFORE UPDATE OF status ON products
FOR EACH ROW
EXECUTE FUNCTION fn_check_product_media_requirements();

