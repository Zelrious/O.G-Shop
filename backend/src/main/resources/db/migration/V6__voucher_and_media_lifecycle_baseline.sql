CREATE TABLE chat_media_daily_quotas (
    conversation_id   BIGINT NOT NULL,
    sender_id         BIGINT NOT NULL,
    quota_date        DATE NOT NULL DEFAULT CURRENT_DATE,
    images_sent       SMALLINT NOT NULL DEFAULT 0,
    videos_sent       SMALLINT NOT NULL DEFAULT 0,
    total_bytes_sent  BIGINT NOT NULL DEFAULT 0,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at        TIMESTAMPTZ,

    CONSTRAINT pk_chat_media_quotas PRIMARY KEY (conversation_id, sender_id, quota_date),
    CONSTRAINT fk_chat_quotas_conversation FOREIGN KEY (conversation_id) REFERENCES conversations (conversation_id),
    CONSTRAINT fk_chat_quotas_sender FOREIGN KEY (sender_id) REFERENCES users (user_id),
    CONSTRAINT ck_chat_quotas_limits CHECK (
        images_sent <= 5 
        AND videos_sent <= 1
        AND total_bytes_sent <= 47185920 -- 45 MB max per conversation per sender per day
    )
);

CREATE INDEX ix_chat_quotas_date ON chat_media_daily_quotas (quota_date);

-- ---------------------------------------------------------------------------
-- 5. Complaint Evidence Retention (Scheduled auto-clean 3 days post-resolution)
-- ---------------------------------------------------------------------------

ALTER TABLE complaints
    ADD COLUMN evidence_cleanup_due_at TIMESTAMPTZ,
    ADD COLUMN evidence_cleaned_at TIMESTAMPTZ;

CREATE OR REPLACE FUNCTION fn_complaint_resolution_schedule_cleanup()
RETURNS TRIGGER AS $$
BEGIN
    IF NEW.status IN ('RESOLVED', 'REJECTED') AND (OLD.status IS NULL OR OLD.status NOT IN ('RESOLVED', 'REJECTED')) THEN
        IF NEW.resolved_at IS NOT NULL THEN
            NEW.evidence_cleanup_due_at := NEW.resolved_at + INTERVAL '3 days';
        ELSE
            NEW.evidence_cleanup_due_at := CURRENT_TIMESTAMP + INTERVAL '3 days';
        END IF;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_complaint_cleanup_schedule
BEFORE UPDATE OF status ON complaints
FOR EACH ROW
EXECUTE FUNCTION fn_complaint_resolution_schedule_cleanup();

CREATE INDEX ix_complaints_cleanup_due ON complaints (status, evidence_cleanup_due_at)
    WHERE evidence_cleaned_at IS NULL AND evidence_cleanup_due_at IS NOT NULL;
