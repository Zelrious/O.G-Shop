-- Migration V34: GHN Webhook Events & Shipment Claim/Lease Support
-- 1. Add claim/lease and incident fields to shipments table
ALTER TABLE shipments ADD COLUMN IF NOT EXISTS claim_token VARCHAR(64);
ALTER TABLE shipments ADD COLUMN IF NOT EXISTS claim_expires_at TIMESTAMPTZ;
ALTER TABLE shipments ADD COLUMN IF NOT EXISTS incident_notes TEXT;
ALTER TABLE shipments ADD COLUMN IF NOT EXISTS admin_review_required BOOLEAN NOT NULL DEFAULT FALSE;

CREATE INDEX IF NOT EXISTS ix_shipments_claim_expires
    ON shipments (claim_expires_at)
    WHERE claim_expires_at IS NOT NULL;

-- 2. Create ghn_webhook_events table for durable webhook ingestion
CREATE TABLE IF NOT EXISTS ghn_webhook_events (
    event_id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_code          VARCHAR(100),
    client_order_code   VARCHAR(100),
    type                VARCHAR(50) NOT NULL,
    event_time          TIMESTAMPTZ,
    idempotency_key     VARCHAR(190) NOT NULL UNIQUE,
    raw_payload         TEXT NOT NULL,
    status              VARCHAR(30) NOT NULL DEFAULT 'PENDING',
    retry_count         INT NOT NULL DEFAULT 0,
    last_error          TEXT,
    received_at         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    processed_at        TIMESTAMPTZ,
    processing_started_at TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS ix_ghn_webhook_events_status
    ON ghn_webhook_events (status, received_at);

CREATE INDEX IF NOT EXISTS ix_ghn_webhook_events_order_code
    ON ghn_webhook_events (order_code);

CREATE INDEX IF NOT EXISTS ix_ghn_webhook_events_recovery
    ON ghn_webhook_events (status, processing_started_at, retry_count);

