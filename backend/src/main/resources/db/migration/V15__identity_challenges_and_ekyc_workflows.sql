CREATE FUNCTION og_guard_ekyc_attempt() RETURNS TRIGGER
LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
DECLARE p ekyc_profiles;
BEGIN
    SELECT * INTO STRICT p FROM ekyc_profiles WHERE profile_id=NEW.profile_id FOR UPDATE;
    IF p.state NOT IN ('DRAFT','IN_PROGRESS') THEN
        RAISE EXCEPTION 'eKYC input is closed' USING ERRCODE='23514';
    END IF;
    NEW.attempted_at := clock_timestamp();
    IF NEW.result='MANUAL_REVIEW' AND NOT og_has_role(NEW.fallback_authorized_by,'ADMIN') THEN
        RAISE EXCEPTION 'Manual fallback requires Admin' USING ERRCODE='23514';
    END IF;
    IF NEW.result='NON_MATCH' THEN
        IF p.nonmatch_count >= 15 OR
           (p.last_nonmatch_at IS NOT NULL AND NEW.attempted_at < p.last_nonmatch_at + INTERVAL '3 seconds') THEN
            RAISE EXCEPTION 'eKYC attempt limit/cooldown' USING ERRCODE='23514';
        END IF;
        UPDATE ekyc_profiles SET nonmatch_count=nonmatch_count+1,last_nonmatch_at=NEW.attempted_at
            WHERE profile_id=p.profile_id;
    END IF;
    RETURN NEW;
END;
$$;
