BEGIN
    SELECT * INTO STRICT c FROM auth_challenges WHERE challenge_id=p_challenge FOR UPDATE;
    IF c.state<>'OPEN' OR c.expires_at<=clock_timestamp() OR c.attempt_count>=c.max_attempts THEN RETURN FALSE; END IF;
    UPDATE auth_challenges SET attempt_count=attempt_count+1,
        state=CASE WHEN code_digest=p_digest THEN 'CONSUMED' ELSE 'OPEN' END,
        consumed_at=CASE WHEN code_digest=p_digest THEN clock_timestamp() END WHERE challenge_id=c.challenge_id;
    RETURN c.code_digest=p_digest;
END;
$$;
CREATE FUNCTION og_guard_auth_challenge_history() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP='DELETE' OR ROW(NEW.challenge_id,NEW.user_id,NEW.subject_key,NEW.purpose,NEW.code_digest,
        NEW.issued_at,NEW.expires_at,NEW.next_send_at,NEW.max_attempts,NEW.command_key) IS DISTINCT FROM
        ROW(OLD.challenge_id,OLD.user_id,OLD.subject_key,OLD.purpose,OLD.code_digest,OLD.issued_at,
        OLD.expires_at,OLD.next_send_at,OLD.max_attempts,OLD.command_key)
        OR OLD.state<>'OPEN' OR NEW.attempt_count<OLD.attempt_count
        OR (NEW.state='CONSUMED' AND (NEW.attempt_count<>OLD.attempt_count+1
            OR OLD.attempt_count>=OLD.max_attempts OR clock_timestamp()>=OLD.expires_at
            OR NEW.consumed_at<OLD.issued_at OR NEW.consumed_at>=OLD.expires_at)) THEN
        RAISE EXCEPTION 'Challenge deadline/digest/consumption history retained' USING ERRCODE='23514'; END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER trg_auth_challenge_retained BEFORE UPDATE OR DELETE ON auth_challenges
    FOR EACH ROW EXECUTE FUNCTION og_guard_auth_challenge_history();
CREATE FUNCTION og_guard_seller_snapshot() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP='DELETE' OR NEW.user_id<>OLD.user_id OR NEW.revision_no<OLD.revision_no
        OR (OLD.state IN ('APPROVED','REJECTED') AND NEW.revision_no=OLD.revision_no AND
            ROW(NEW.state,NEW.ekyc_profile_id,NEW.quick_auth_result_id,NEW.pickup_address_id,NEW.bank_snapshot)
            IS DISTINCT FROM ROW(OLD.state,OLD.ekyc_profile_id,OLD.quick_auth_result_id,OLD.pickup_address_id,OLD.bank_snapshot))
        OR (NEW.revision_no>OLD.revision_no AND (NEW.revision_no<>OLD.revision_no+1 OR NEW.state NOT IN ('PENDING_EKYC','PENDING_REVIEW'))) THEN
        RAISE EXCEPTION 'Seller snapshot changes require a new review revision' USING ERRCODE='23514'; END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER trg_seller_snapshot BEFORE UPDATE OR DELETE ON seller_profiles
    FOR EACH ROW EXECUTE FUNCTION og_guard_seller_snapshot();
