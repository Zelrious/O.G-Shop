-- Final states need the corresponding immutable decision in the same transaction.
CREATE FUNCTION og_validate_identity_decision() RETURNS TRIGGER
LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
BEGIN
    IF TG_TABLE_NAME='ekyc_profiles' THEN
        IF EXISTS(SELECT 1 FROM ekyc_profiles p WHERE p.profile_id=NEW.profile_id
            AND p.state IN ('VERIFIED','REJECTED') AND NOT EXISTS(SELECT 1 FROM ekyc_decisions d
                WHERE d.profile_id=p.profile_id AND d.outcome=p.state)) THEN
            RAISE EXCEPTION 'Final eKYC state requires KTV decision' USING ERRCODE='23514';
        END IF;
    ELSE
        IF EXISTS(SELECT 1 FROM seller_profiles p WHERE p.seller_profile_id=NEW.seller_profile_id
            AND p.state IN ('APPROVED','REJECTED') AND NOT EXISTS(SELECT 1 FROM seller_profile_decisions d
                WHERE d.seller_profile_id=p.seller_profile_id AND d.revision_no=p.revision_no AND d.outcome=p.state)) THEN
            RAISE EXCEPTION 'Final seller state requires KTV decision' USING ERRCODE='23514';
        END IF;
    END IF;
    RETURN NULL;
END;
$$;
