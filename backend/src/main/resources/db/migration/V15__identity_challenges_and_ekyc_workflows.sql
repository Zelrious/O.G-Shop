        ROW(OLD.profile_id,OLD.user_id,OLD.revision_no,OLD.created_at)
        OR (OLD.state IN ('PENDING','VERIFIED','REJECTED','EXPIRED') AND
            ROW(NEW.submitted_data,NEW.ai_summary,NEW.document_digest,NEW.submitted_at) IS DISTINCT FROM
            ROW(OLD.submitted_data,OLD.ai_summary,OLD.document_digest,OLD.submitted_at))
        OR (OLD.state IN ('VERIFIED','REJECTED','EXPIRED') AND NEW.state<>OLD.state
            AND NOT (OLD.state='VERIFIED' AND NEW.state='EXPIRED')))) THEN
        RAISE EXCEPTION 'eKYC identity/submitted evidence is immutable' USING ERRCODE='23514';
    END IF;
    RETURN NEW;
END;
$$;
