CREATE FUNCTION og_apply_ekyc_decision() RETURNS TRIGGER
LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
DECLARE p ekyc_profiles;
BEGIN
    NEW.decided_at:=clock_timestamp();
    SELECT * INTO STRICT p FROM ekyc_profiles WHERE profile_id=NEW.profile_id FOR UPDATE;
    IF p.state<>'PENDING' OR NOT og_has_role(NEW.reviewed_by,'KTV') THEN
        RAISE EXCEPTION 'Only KTV can decide a pending eKYC revision' USING ERRCODE='23514';
    END IF;
    IF NEW.outcome='VERIFIED' AND (
        p.document_digest IS NULL
        OR (SELECT count(DISTINCT asset_type) FROM ekyc_private_assets
            WHERE profile_id=p.profile_id AND deleted_at IS NULL AND expires_at>NEW.decided_at
              AND asset_type IN ('CARD_FRONT','CARD_BACK','LIVE_FRAME','REFERENCE')) <> 4) THEN
        RAISE EXCEPTION 'eKYC identity/private evidence incomplete' USING ERRCODE='23514';
    END IF;
    UPDATE ekyc_profiles SET state=NEW.outcome,
        verified_at=CASE WHEN NEW.outcome='VERIFIED' THEN NEW.decided_at END,
        reference_expires_at=CASE WHEN NEW.outcome='VERIFIED' THEN
            LEAST(NEW.decided_at+INTERVAL '3 months',
                (SELECT min(expires_at) FROM ekyc_private_assets WHERE profile_id=p.profile_id AND deleted_at IS NULL)) END,
        version=version+1 WHERE profile_id=p.profile_id;
    RETURN NEW;
END;
$$;
