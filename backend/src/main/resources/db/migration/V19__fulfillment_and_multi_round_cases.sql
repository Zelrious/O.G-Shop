CREATE FUNCTION og_guard_pickup_attempt() RETURNS TRIGGER
LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
DECLARE s shipments;
BEGIN
    SELECT * INTO STRICT s FROM shipments WHERE shipment_id=NEW.shipment_id FOR UPDATE;
    IF s.workflow_model<>'UC83' OR s.leg<>'RETURN' OR NEW.attempted_at<s.initiated_at OR NEW.attempted_at>s.pickup_deadline
       OR NEW.attempt_no<>(SELECT count(*)+1 FROM pickup_attempts WHERE shipment_id=s.shipment_id)
       OR (SELECT count(*) FROM pickup_attempts WHERE shipment_id=s.shipment_id AND outcome='FAILED')>=3
       OR EXISTS(SELECT 1 FROM pickup_attempts WHERE shipment_id=s.shipment_id AND outcome='PICKED_UP')
       OR NOT EXISTS(SELECT 1 FROM shipment_events WHERE event_id=NEW.source_event_id AND shipment_id=s.shipment_id) THEN
        RAISE EXCEPTION 'Pickup deadline/count/source exceeded' USING ERRCODE='23514';
    END IF;
    RETURN NEW;
END;
$$;
