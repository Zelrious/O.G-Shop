CREATE TABLE case_evidence (
    evidence_id UUID PRIMARY KEY,
    round_id BIGINT NOT NULL REFERENCES case_rounds(round_id),
    submitted_by BIGINT NOT NULL REFERENCES users(user_id),
    submission_no INTEGER NOT NULL CHECK(submission_no>0),
    media_type VARCHAR(10) NOT NULL CHECK(media_type IN ('IMAGE','VIDEO','TEXT')),
    object_key TEXT,
    text_content TEXT,
    content_digest CHAR(64),
    file_size_bytes BIGINT,
    duration_seconds INTEGER,
    submitted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted_at TIMESTAMPTZ,
    CHECK((media_type='TEXT' AND NULLIF(btrim(text_content),'') IS NOT NULL AND object_key IS NULL)
       OR (media_type IN ('IMAGE','VIDEO') AND NULLIF(btrim(object_key),'') IS NOT NULL
         AND content_digest IS NOT NULL AND content_digest ~ '^[0-9a-f]{64}$' AND file_size_bytes IS NOT NULL AND file_size_bytes>0
         AND ((media_type='IMAGE' AND file_size_bytes<=5242880)
           OR (media_type='VIDEO' AND file_size_bytes<=52428800 AND duration_seconds IS NOT NULL AND duration_seconds BETWEEN 1 AND 60))))
);
CREATE FUNCTION og_guard_case_evidence() RETURNS TRIGGER
LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
DECLARE r case_rounds; c cases; o orders; n INTEGER;
BEGIN
    SELECT * INTO STRICT r FROM case_rounds WHERE round_id=NEW.round_id FOR UPDATE;
    SELECT * INTO STRICT c FROM cases WHERE case_id=r.case_id;
    IF r.state<>'OPEN' THEN RAISE EXCEPTION 'Evidence round closed' USING ERRCODE='23514'; END IF;
    NEW.submitted_at:=clock_timestamp();
    IF c.order_id IS NOT NULL THEN
        SELECT * INTO STRICT o FROM orders WHERE order_id=c.order_id;
        IF NEW.submitted_by NOT IN (o.buyer_id,o.seller_id) AND NOT og_has_role(NEW.submitted_by,'KTV') THEN
            RAISE EXCEPTION 'Evidence author not a party/KTV' USING ERRCODE='23514';
        END IF;
        IF NEW.submitted_by=o.buyer_id AND c.case_type='RETURN'
            AND NEW.submitted_at>o.valid_delivered_at+INTERVAL '3 days' THEN
            RAISE EXCEPTION 'Buyer evidence submission deadline passed' USING ERRCODE='23514';
        END IF;
    ELSIF NEW.submitted_by<>c.created_by AND NOT og_has_role(NEW.submitted_by,'KTV') THEN
        RAISE EXCEPTION 'Private system issue evidence author invalid' USING ERRCODE='23514';
    END IF;
    SELECT count(*) INTO n FROM case_evidence WHERE round_id=NEW.round_id
        AND submitted_by=NEW.submitted_by AND submission_no=NEW.submission_no AND media_type=NEW.media_type;
    IF (NEW.media_type='IMAGE' AND n>=5) OR (NEW.media_type='VIDEO' AND n>=2) THEN
        RAISE EXCEPTION 'Evidence submission media limit exceeded' USING ERRCODE='23514';
    END IF;
    RETURN NEW;
END;
$$;
