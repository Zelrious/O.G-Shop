    state VARCHAR(15) NOT NULL DEFAULT 'OPEN' CHECK(state IN ('OPEN','DECIDED')),
    opened_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    complete_submission_at TIMESTAMPTZ,
    ktv_due_at TIMESTAMPTZ,
    valid_damage_request_at TIMESTAMPTZ,
    UNIQUE(case_id,round_no),
    UNIQUE(round_id,case_id),
