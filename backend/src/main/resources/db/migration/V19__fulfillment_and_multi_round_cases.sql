-- G08/G09. One case owns multiple rounds; shipping directions retain separate identities.
CREATE TABLE cases (
    case_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_type VARCHAR(20) NOT NULL CHECK(case_type IN ('RETURN','SYSTEM_ISSUE')),
    order_id BIGINT REFERENCES orders(order_id),
    product_id BIGINT REFERENCES products(product_id),
    listing_charge_id UUID REFERENCES listing_fee_charges(charge_id),
    payment_intent_id UUID REFERENCES payment_intents(intent_id),
    target_user_id BIGINT REFERENCES users(user_id),
    created_by BIGINT NOT NULL REFERENCES users(user_id),
    assigned_to BIGINT REFERENCES users(user_id),
    description TEXT NOT NULL CHECK(btrim(description)<>''),
    state VARCHAR(20) NOT NULL DEFAULT 'OPEN' CHECK(state IN ('OPEN','REVIEWING','RETURN_APPROVED','RETURNING','POST_RETURN','CLOSED','REJECTED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    approved_at TIMESTAMPTZ,
    valid_returned_at TIMESTAMPTZ,
    seller_response_due_at TIMESTAMPTZ,
    closed_at TIMESTAMPTZ,
    last_related_completion_at TIMESTAMPTZ,
    command_key VARCHAR(150) NOT NULL UNIQUE,
    CHECK((order_id IS NOT NULL)::INTEGER+(product_id IS NOT NULL)::INTEGER+
        (listing_charge_id IS NOT NULL)::INTEGER+(payment_intent_id IS NOT NULL)::INTEGER+
        (target_user_id IS NOT NULL)::INTEGER=1),
    CHECK(case_type<>'RETURN' OR order_id IS NOT NULL),
    CHECK(valid_returned_at IS NULL OR (approved_at IS NOT NULL AND valid_returned_at>=approved_at
        AND seller_response_due_at=valid_returned_at+INTERVAL '2 days')),
    CHECK(state NOT IN ('CLOSED','REJECTED') OR closed_at IS NOT NULL)
);
CREATE UNIQUE INDEX uq_return_case_active ON cases(order_id)
    WHERE case_type='RETURN' AND state NOT IN ('CLOSED','REJECTED');
CREATE INDEX ix_case_work_queue ON cases(assigned_to,state,created_at,case_id);
CREATE FUNCTION og_guard_return_case() RETURNS TRIGGER
LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
DECLARE o orders;
BEGIN
    IF NEW.state<>'OPEN' THEN RAISE EXCEPTION 'New case starts open' USING ERRCODE='23514'; END IF;
    IF NEW.case_type='RETURN' AND TG_OP='INSERT' THEN
        SELECT * INTO STRICT o FROM orders WHERE order_id=NEW.order_id FOR UPDATE;
        NEW.created_at:=clock_timestamp();
        IF o.workflow_model<>'UC83' OR NEW.created_by<>o.buyer_id OR NOT o.return_allowed
            OR o.valid_delivered_at IS NULL OR o.early_completed_at IS NOT NULL
            OR NEW.created_at>o.valid_delivered_at+INTERVAL '3 days' THEN
            RAISE EXCEPTION 'Order has no current right to request return' USING ERRCODE='23514';
        END IF;
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER trg_return_case_guard BEFORE INSERT ON cases FOR EACH ROW EXECUTE FUNCTION og_guard_return_case();

