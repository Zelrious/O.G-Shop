CREATE FUNCTION og_guard_case_event() RETURNS TRIGGER
LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
DECLARE c cases; o orders;
BEGIN
    SELECT * INTO STRICT c FROM cases WHERE case_id=NEW.case_id FOR UPDATE;
    NEW.occurred_at:=clock_timestamp();
    IF NEW.event_type='ESCALATED' AND (NOT og_has_role(NEW.actor_id,'KTV') OR
        NOT og_has_role(NEW.recipient_id,'ADMIN')) THEN
        RAISE EXCEPTION 'Escalation needs KTV to Admin' USING ERRCODE='23514';
    END IF;
    IF NEW.event_type='VALID_DAMAGE_REQUEST' THEN
        SELECT * INTO STRICT o FROM orders WHERE order_id=c.order_id;
        IF NEW.actor_id<>o.seller_id OR c.valid_returned_at IS NULL OR NEW.occurred_at>c.seller_response_due_at
            OR NOT EXISTS(SELECT 1 FROM case_rounds WHERE round_id=NEW.round_id
                AND stage='POST_RETURN_RESOLUTION' AND state='OPEN')
            OR NOT EXISTS(SELECT 1 FROM case_evidence WHERE round_id=NEW.round_id AND submitted_by=NEW.actor_id) THEN
            RAISE EXCEPTION 'Only complete in-time Seller request blocks auto refund' USING ERRCODE='23514';
        END IF;
        UPDATE case_rounds SET valid_damage_request_at=NEW.occurred_at WHERE round_id=NEW.round_id;
    END IF;
    RETURN NEW;
END;
$$;
