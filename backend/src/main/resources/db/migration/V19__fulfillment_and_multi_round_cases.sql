CREATE FUNCTION og_validate_case_state() RETURNS TRIGGER
LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
DECLARE c cases;
BEGIN
    SELECT * INTO STRICT c FROM cases WHERE case_id=NEW.case_id;
    IF (c.approved_at IS NOT NULL AND NOT EXISTS(SELECT 1 FROM case_decisions d JOIN case_rounds r USING(round_id)
        WHERE r.case_id=c.case_id AND d.outcome='APPROVE_RETURN' AND d.is_final))
        OR (c.state IN ('CLOSED','REJECTED') AND NOT EXISTS(SELECT 1 FROM case_decisions d JOIN case_rounds r USING(round_id)
            WHERE r.case_id=c.case_id AND d.is_final AND d.outcome IN
                ('REJECT_RETURN','FULL_GOODS_REFUND','EXEMPT_GOODS_REFUND','SYSTEM_RESOLVED')))
        OR (c.valid_returned_at IS NOT NULL AND NOT EXISTS(SELECT 1 FROM shipments s
            WHERE s.return_case_id=c.case_id AND s.leg='RETURN' AND s.valid_delivery_at=c.valid_returned_at)) THEN
        RAISE EXCEPTION 'Case state requires corresponding decision/delivery proof' USING ERRCODE='23514';
    END IF;
    RETURN NULL;
END;
$$;
CREATE CONSTRAINT TRIGGER trg_case_state_proof AFTER INSERT OR UPDATE ON cases
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION og_validate_case_state();
CREATE FUNCTION og_close_case_holds() RETURNS TRIGGER
LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
BEGIN
    UPDATE money_holds SET closed_at=clock_timestamp() WHERE case_id=(SELECT r.case_id FROM case_rounds r
        WHERE r.round_id=NEW.round_id) AND closed_at IS NULL AND EXISTS(SELECT 1 FROM cases c
        WHERE c.case_id=money_holds.case_id AND c.state IN ('CLOSED','REJECTED'));
    RETURN NEW;
END;
$$;
CREATE TRIGGER trg_case_close_holds AFTER INSERT ON case_decisions
    FOR EACH ROW EXECUTE FUNCTION og_close_case_holds();
