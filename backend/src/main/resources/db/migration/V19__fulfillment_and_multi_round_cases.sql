CREATE FUNCTION og_guard_return_shipment() RETURNS TRIGGER
LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
DECLARE c cases;
BEGIN
    IF NEW.workflow_model='UC83' AND NEW.leg='RETURN' THEN
        SELECT * INTO STRICT c FROM cases WHERE case_id=NEW.return_case_id FOR UPDATE;
        IF c.order_id<>NEW.order_id OR c.case_type<>'RETURN' OR c.approved_at IS NULL THEN
            RAISE EXCEPTION 'Return shipment requires approval for the same order' USING ERRCODE='23514';
        END IF;
        NEW.pickup_expected_at:=c.approved_at+INTERVAL '24 hours';
        NEW.pickup_deadline:=c.approved_at+INTERVAL '3 days';
    END IF;
    IF TG_OP='UPDATE' AND NEW.workflow_model='UC83' AND
        ROW(NEW.order_id,NEW.leg,NEW.return_case_id,NEW.delivery_method,NEW.initiated_at)
        IS DISTINCT FROM ROW(OLD.order_id,OLD.leg,OLD.return_case_id,OLD.delivery_method,OLD.initiated_at) THEN
        RAISE EXCEPTION 'Shipment identity/method snapshot cannot silently change' USING ERRCODE='23514';
    END IF;
    RETURN NEW;
END;
$$;
