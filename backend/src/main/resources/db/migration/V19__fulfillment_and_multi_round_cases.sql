CREATE FUNCTION og_confirm_direct_handover(p_shipment BIGINT) RETURNS BOOLEAN
LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
DECLARE s shipments; delivered TIMESTAMPTZ;
BEGIN
    PERFORM 1 FROM orders WHERE order_id=(SELECT order_id FROM shipments WHERE shipment_id=p_shipment) FOR UPDATE;
    SELECT * INTO STRICT s FROM shipments WHERE shipment_id=p_shipment FOR UPDATE;
    IF s.workflow_model<>'UC83' OR s.delivery_method='CARRIER' THEN
        RAISE EXCEPTION 'Direct handover only' USING ERRCODE='23514'; END IF;
    IF s.valid_delivery_at IS NOT NULL THEN RETURN TRUE; END IF;
    IF EXISTS(SELECT 1 FROM handover_confirmations WHERE shipment_id=p_shipment AND outcome='FAILED') THEN RETURN FALSE; END IF;
    IF s.otp_consumed_at IS NOT NULL THEN delivered:=s.otp_consumed_at;
    ELSIF (SELECT count(*) FROM handover_confirmations WHERE shipment_id=p_shipment AND outcome='SUCCESS')=2 THEN
        SELECT max(confirmed_at) INTO delivered FROM handover_confirmations WHERE shipment_id=p_shipment;
    ELSE RETURN FALSE; END IF;
    UPDATE shipments SET valid_delivery_at=delivered,status='DELIVERED',shipped_at=COALESCE(shipped_at,initiated_at),
        delivered_at=delivered WHERE shipment_id=p_shipment;
    IF s.leg='RETURN' THEN
        UPDATE cases SET state='POST_RETURN',valid_returned_at=delivered,seller_response_due_at=delivered+INTERVAL '2 days'
            WHERE case_id=s.return_case_id;
    ELSIF s.leg='OUTBOUND' THEN
        UPDATE orders SET status='DELIVERED',valid_delivered_at=delivered,
            return_due_at=CASE WHEN return_allowed THEN delivered+INTERVAL '3 days' END WHERE order_id=s.order_id;
    END IF;
    RETURN TRUE;
END;
$$;
CREATE FUNCTION og_consume_handover_otp(p_shipment BIGINT,p_buyer BIGINT,p_digest TEXT) RETURNS BOOLEAN
LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
DECLARE s shipments;
BEGIN
    PERFORM 1 FROM orders WHERE order_id=(SELECT order_id FROM shipments WHERE shipment_id=p_shipment) FOR UPDATE;
    SELECT * INTO STRICT s FROM shipments WHERE shipment_id=p_shipment FOR UPDATE;
    IF s.workflow_model<>'UC83' OR s.delivery_method='CARRIER' OR NOT EXISTS(SELECT 1 FROM orders
        WHERE order_id=s.order_id AND buyer_id=p_buyer) OR s.otp_digest IS NULL OR s.otp_consumed_at IS NOT NULL
        OR s.otp_expires_at<=clock_timestamp() OR s.otp_attempt_count>=5 THEN RETURN FALSE; END IF;
    UPDATE shipments SET otp_attempt_count=otp_attempt_count+1,
        otp_consumed_at=CASE WHEN otp_digest=p_digest THEN clock_timestamp() END WHERE shipment_id=p_shipment;
    IF s.otp_digest<>p_digest THEN RETURN FALSE; END IF;
    RETURN og_confirm_direct_handover(p_shipment);
END;
$$;
CREATE FUNCTION og_early_complete_order(p_order BIGINT,p_buyer BIGINT,p_warning TEXT,p_command TEXT) RETURNS BOOLEAN
LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
DECLARE o orders;
BEGIN
    SELECT * INTO STRICT o FROM orders WHERE order_id=p_order FOR UPDATE;
    IF EXISTS(SELECT 1 FROM order_events WHERE command_key=p_command AND order_id=p_order AND actor_id=p_buyer
        AND event_type='EARLY_COMPLETION_ACCEPTED') THEN RETURN TRUE; END IF;
    IF o.workflow_model<>'UC83' OR o.buyer_id<>p_buyer OR o.valid_delivered_at IS NULL
        OR NULLIF(btrim(p_warning),'') IS NULL OR o.status<>'DELIVERED' OR og_order_has_blocking_case(p_order)
        OR EXISTS(SELECT 1 FROM money_holds h JOIN order_fund_components c USING(component_id)
            WHERE c.order_id=p_order AND h.closed_at IS NULL) THEN
        RAISE EXCEPTION 'Early completion needs Buyer warning consent and no blockers' USING ERRCODE='23514'; END IF;
    UPDATE orders SET early_completed_at=clock_timestamp(),early_completion_warning_version=p_warning WHERE order_id=p_order;
    INSERT INTO order_events(event_id,order_id,actor_id,event_type,metadata,command_key)
        VALUES(gen_random_uuid(),p_order,p_buyer,'EARLY_COMPLETION_ACCEPTED',jsonb_build_object('warning_version',p_warning),p_command);
    RETURN TRUE;
END;
$$;
