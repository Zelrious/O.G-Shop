-- 5. Commerce & Cart
-- ============================================================================

CREATE TABLE carts (
    cart_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT NOT NULL UNIQUE,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at       TIMESTAMPTZ,

    CONSTRAINT fk_carts_user FOREIGN KEY (user_id) REFERENCES users (user_id)
);

CREATE TABLE cart_items (
    cart_id          BIGINT NOT NULL,
    product_id       BIGINT NOT NULL,
    quantity         SMALLINT NOT NULL DEFAULT 1,
    added_at         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_cart_items PRIMARY KEY (cart_id, product_id),
    CONSTRAINT fk_cart_items_cart FOREIGN KEY (cart_id) REFERENCES carts (cart_id) ON DELETE CASCADE,
    CONSTRAINT fk_cart_items_product FOREIGN KEY (product_id) REFERENCES products (product_id),
    CONSTRAINT ck_cart_items_mvp_quantity CHECK (quantity = 1)
);

CREATE INDEX ix_cart_items_product_id ON cart_items (product_id);

CREATE TABLE orders (
    order_id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    checkout_group_id           UUID NOT NULL,
    buyer_id                    BIGINT NOT NULL,
    seller_id                   BIGINT NOT NULL,
    source_address_id           BIGINT,
    shipping_recipient_name     VARCHAR(120) NOT NULL,
    shipping_phone_number       VARCHAR(20) NOT NULL,
    shipping_province           VARCHAR(100) NOT NULL,
    shipping_district           VARCHAR(100) NOT NULL,
    shipping_ward               VARCHAR(100) NOT NULL,
    shipping_detail_address     VARCHAR(255) NOT NULL,
    subtotal                    NUMERIC(19,2) NOT NULL,
    shipping_fee                NUMERIC(19,2) NOT NULL DEFAULT 0,
    total_amount                NUMERIC(19,2) NOT NULL,
    currency                    CHAR(3) NOT NULL DEFAULT 'VND',
    status                      VARCHAR(30) NOT NULL DEFAULT 'PAYMENT_PENDING',
    payment_due_at              TIMESTAMPTZ NOT NULL,
    version                     BIGINT NOT NULL DEFAULT 0,
    created_at                  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at                  TIMESTAMPTZ,
    completed_at                TIMESTAMPTZ,
    cancelled_at                TIMESTAMPTZ,
    cancellation_reason         VARCHAR(500),

    CONSTRAINT fk_orders_buyer FOREIGN KEY (buyer_id) REFERENCES users (user_id),
    CONSTRAINT fk_orders_seller FOREIGN KEY (seller_id) REFERENCES users (user_id),
    CONSTRAINT fk_orders_source_address FOREIGN KEY (source_address_id) REFERENCES addresses (address_id) ON DELETE SET NULL,
    CONSTRAINT ck_orders_distinct_users CHECK (buyer_id <> seller_id),
    CONSTRAINT ck_orders_amounts CHECK (subtotal > 0 AND shipping_fee >= 0 AND total_amount = subtotal + shipping_fee),
    CONSTRAINT ck_orders_currency CHECK (currency = 'VND'),
    CONSTRAINT ck_orders_status CHECK (status IN (
        'PAYMENT_PENDING', 'PAID_HELD', 'SELLER_CONFIRMED', 'SHIPPED', 'DELIVERED',
        'COMPLETED', 'CANCELLED', 'DISPUTED', 'REFUNDED'
    )),
    CONSTRAINT ck_orders_payment_due CHECK (payment_due_at > created_at),
    CONSTRAINT ck_orders_terminal_time CHECK (
        (status = 'COMPLETED' AND completed_at IS NOT NULL AND cancelled_at IS NULL AND cancellation_reason IS NULL)
        OR
        (status = 'CANCELLED' AND cancelled_at IS NOT NULL AND completed_at IS NULL AND cancellation_reason IS NOT NULL)
        OR
        (status NOT IN ('COMPLETED', 'CANCELLED') AND completed_at IS NULL AND cancelled_at IS NULL AND cancellation_reason IS NULL)
    )
);

CREATE INDEX ix_orders_buyer_created ON orders (buyer_id, created_at DESC);
CREATE INDEX ix_orders_seller_created ON orders (seller_id, created_at DESC);
CREATE INDEX ix_orders_checkout_group ON orders (buyer_id, checkout_group_id);
CREATE INDEX ix_orders_status_created ON orders (status, created_at);
CREATE INDEX ix_orders_source_address_id ON orders (source_address_id) WHERE source_address_id IS NOT NULL;
CREATE INDEX ix_orders_payment_expiry ON orders (payment_due_at) WHERE status = 'PAYMENT_PENDING';

CREATE TABLE order_items (
    order_item_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id         BIGINT NOT NULL,
    product_id       BIGINT NOT NULL,
    product_title    VARCHAR(200) NOT NULL,
    quantity         SMALLINT NOT NULL DEFAULT 1,
    unit_price       NUMERIC(19,2) NOT NULL,
    line_total       NUMERIC(19,2) NOT NULL,

    CONSTRAINT fk_order_items_order FOREIGN KEY (order_id) REFERENCES orders (order_id),
    CONSTRAINT fk_order_items_product FOREIGN KEY (product_id) REFERENCES products (product_id),
    CONSTRAINT uq_order_items_order_product UNIQUE (order_id, product_id),
    CONSTRAINT ck_order_items_mvp_quantity CHECK (quantity = 1),
    CONSTRAINT ck_order_items_price CHECK (unit_price > 0 AND line_total = unit_price * quantity)
);

CREATE INDEX ix_order_items_product_id ON order_items (product_id);

ALTER TABLE products
    ADD CONSTRAINT fk_products_reserved_order_item
    FOREIGN KEY (reserved_order_id, product_id)
    REFERENCES order_items (order_id, product_id);

-- ============================================================================
-- 6. Payments (Escrow / Hold-Release) & Fulfillment
-- ============================================================================

CREATE TABLE payments (
    payment_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id         BIGINT NOT NULL UNIQUE,
    amount           NUMERIC(19,2) NOT NULL,
    currency         CHAR(3) NOT NULL DEFAULT 'VND',
    payment_method   VARCHAR(30) NOT NULL,
    transaction_code VARCHAR(100),
    status           VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    paid_at          TIMESTAMPTZ,
    version          BIGINT NOT NULL DEFAULT 0,
    held_at          TIMESTAMPTZ,
    released_at      TIMESTAMPTZ,
    refund_amount    NUMERIC(19,2),
    refund_reason    VARCHAR(500),
    refunded_at      TIMESTAMPTZ,
    failure_reason   VARCHAR(500),
    created_at       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at       TIMESTAMPTZ,

    CONSTRAINT fk_payments_order FOREIGN KEY (order_id) REFERENCES orders (order_id),
    CONSTRAINT uq_payments_transaction_code UNIQUE (transaction_code),
    CONSTRAINT ck_payments_amount CHECK (amount > 0),
    CONSTRAINT ck_payments_currency CHECK (currency = 'VND'),
    CONSTRAINT ck_payments_method CHECK (payment_method IN ('COD_MOCK', 'BANK_TRANSFER_MOCK', 'E_WALLET_MOCK')),
    CONSTRAINT ck_payments_status CHECK (status IN ('PENDING', 'PAID', 'HELD', 'RELEASED', 'REFUND_PENDING', 'REFUNDED', 'FAILED')),
    CONSTRAINT ck_payments_refund_amount CHECK (refund_amount IS NULL OR refund_amount = amount),
    CONSTRAINT ck_payments_state_fields CHECK (
        (status = 'PENDING' AND paid_at IS NULL AND held_at IS NULL AND released_at IS NULL AND refunded_at IS NULL AND failure_reason IS NULL)
        OR
        (status = 'PAID' AND paid_at IS NOT NULL AND held_at IS NULL AND released_at IS NULL AND refunded_at IS NULL AND failure_reason IS NULL)
        OR
        (status = 'HELD' AND paid_at IS NOT NULL AND held_at IS NOT NULL AND held_at >= paid_at AND released_at IS NULL AND refunded_at IS NULL AND failure_reason IS NULL)
        OR
        (status = 'RELEASED' AND paid_at IS NOT NULL AND held_at IS NOT NULL AND held_at >= paid_at AND released_at IS NOT NULL AND released_at >= held_at AND refunded_at IS NULL AND failure_reason IS NULL)
        OR
        (status = 'REFUND_PENDING' AND paid_at IS NOT NULL AND held_at IS NOT NULL AND held_at >= paid_at AND released_at IS NULL AND refunded_at IS NULL AND refund_amount IS NOT NULL AND refund_reason IS NOT NULL AND failure_reason IS NULL)
        OR
        (status = 'REFUNDED' AND paid_at IS NOT NULL AND held_at IS NOT NULL AND held_at >= paid_at AND released_at IS NULL AND refunded_at IS NOT NULL AND refunded_at >= held_at AND refund_amount IS NOT NULL AND refund_reason IS NOT NULL AND failure_reason IS NULL)
        OR
        (status = 'FAILED' AND paid_at IS NULL AND held_at IS NULL AND released_at IS NULL AND refunded_at IS NULL AND failure_reason IS NOT NULL)
    )
);

CREATE INDEX ix_payments_status_created ON payments (status, created_at);

CREATE TABLE shipments (
    shipment_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id         BIGINT NOT NULL UNIQUE,
    carrier          VARCHAR(100),
    tracking_number  VARCHAR(100),
    status           VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    shipped_at       TIMESTAMPTZ,
    delivered_at     TIMESTAMPTZ,
    updated_at       TIMESTAMPTZ,

    CONSTRAINT fk_shipments_order FOREIGN KEY (order_id) REFERENCES orders (order_id),
    CONSTRAINT uq_shipments_tracking_number UNIQUE (tracking_number),
    CONSTRAINT ck_shipments_status CHECK (status IN ('PENDING', 'PICKED_UP', 'IN_TRANSIT', 'DELIVERED', 'RETURNED', 'FAILED')),
    CONSTRAINT ck_shipments_times CHECK (
        (status = 'PENDING' AND shipped_at IS NULL AND delivered_at IS NULL)
        OR
        (status IN ('PICKED_UP', 'IN_TRANSIT', 'RETURNED') AND shipped_at IS NOT NULL AND delivered_at IS NULL)
        OR
        (status = 'DELIVERED' AND shipped_at IS NOT NULL AND delivered_at IS NOT NULL AND delivered_at >= shipped_at)
        OR
        (status = 'FAILED' AND delivered_at IS NULL)
    )
);

CREATE INDEX ix_shipments_status_updated ON shipments (status, updated_at);

