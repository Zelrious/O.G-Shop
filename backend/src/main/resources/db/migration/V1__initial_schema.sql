CREATE TABLE complaints (
    complaint_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id         BIGINT NOT NULL,
    created_by       BIGINT NOT NULL,
    reason           VARCHAR(50) NOT NULL,
    description      TEXT NOT NULL,
    evidence         JSONB NOT NULL DEFAULT '{"images": [], "videos": []}'::jsonb,
    status           VARCHAR(20) NOT NULL DEFAULT 'OPEN',
    resolution       VARCHAR(30),
    resolution_note  TEXT,
    resolved_by      BIGINT,
    refund_amount    NUMERIC(19,2),
    created_at       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    resolved_at      TIMESTAMPTZ,

    CONSTRAINT fk_complaints_order FOREIGN KEY (order_id) REFERENCES orders (order_id),
    CONSTRAINT fk_complaints_created_by FOREIGN KEY (created_by) REFERENCES users (user_id),
    CONSTRAINT fk_complaints_resolved_by FOREIGN KEY (resolved_by) REFERENCES users (user_id),
    CONSTRAINT ck_complaints_reason CHECK (reason IN ('NOT_AS_DESCRIBED', 'DAMAGED', 'COUNTERFEIT', 'MISSING_ITEM', 'DELIVERY_ISSUE', 'OTHER')),
    CONSTRAINT ck_complaints_evidence_object CHECK (jsonb_typeof(evidence) = 'object'),
    CONSTRAINT ck_complaints_status CHECK (status IN ('OPEN', 'REVIEWING', 'RESOLVED', 'REJECTED')),
    CONSTRAINT ck_complaints_resolution CHECK (resolution IS NULL OR resolution IN ('REFUND_BUYER', 'RELEASE_TO_SELLER', 'REJECT_COMPLAINT')),
    CONSTRAINT ck_complaints_refund CHECK (refund_amount IS NULL OR refund_amount > 0),
    CONSTRAINT ck_complaints_resolution_fields CHECK (
        (status IN ('OPEN', 'REVIEWING') AND resolution IS NULL AND resolved_by IS NULL AND resolved_at IS NULL AND refund_amount IS NULL)
        OR
        (status = 'RESOLVED' AND resolution IN ('REFUND_BUYER', 'RELEASE_TO_SELLER') AND resolved_by IS NOT NULL AND resolved_at IS NOT NULL)
        OR
        (status = 'REJECTED' AND resolution = 'REJECT_COMPLAINT' AND resolved_by IS NOT NULL AND resolved_at IS NOT NULL AND refund_amount IS NULL)
    ),
    CONSTRAINT ck_complaints_refund_resolution CHECK (
        (resolution = 'REFUND_BUYER' AND refund_amount IS NOT NULL)
        OR (resolution IS DISTINCT FROM 'REFUND_BUYER' AND refund_amount IS NULL)
    )
);

CREATE INDEX ix_complaints_order_id ON complaints (order_id);
CREATE INDEX ix_complaints_created_by ON complaints (created_by);
CREATE INDEX ix_complaints_resolved_by ON complaints (resolved_by) WHERE resolved_by IS NOT NULL;
CREATE INDEX ix_complaints_status_created ON complaints (status, created_at);
