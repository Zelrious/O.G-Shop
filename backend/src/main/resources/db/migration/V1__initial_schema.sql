CREATE TABLE conversations (
    conversation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    buyer_id         BIGINT NOT NULL,
    seller_id        BIGINT NOT NULL,
    product_id       BIGINT NOT NULL,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_message_at  TIMESTAMPTZ,

    CONSTRAINT fk_conversations_buyer FOREIGN KEY (buyer_id) REFERENCES users (user_id),
    CONSTRAINT fk_conversations_seller FOREIGN KEY (seller_id) REFERENCES users (user_id),
    CONSTRAINT fk_conversations_product FOREIGN KEY (product_id) REFERENCES products (product_id),
    CONSTRAINT ck_conversations_distinct_users CHECK (buyer_id <> seller_id),
    CONSTRAINT uq_conversations_parties_product UNIQUE (buyer_id, seller_id, product_id)
);

CREATE INDEX ix_conversations_buyer_recent ON conversations (buyer_id, last_message_at DESC NULLS LAST);
CREATE INDEX ix_conversations_seller_recent ON conversations (seller_id, last_message_at DESC NULLS LAST);
CREATE INDEX ix_conversations_product_id ON conversations (product_id);

CREATE TABLE messages (
    message_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id  BIGINT NOT NULL,
    sender_id        BIGINT NOT NULL,
    content          TEXT NOT NULL,
    message_type     VARCHAR(10) NOT NULL DEFAULT 'TEXT',
    created_at       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    read_at          TIMESTAMPTZ,

    CONSTRAINT fk_messages_conversation FOREIGN KEY (conversation_id) REFERENCES conversations (conversation_id),
    CONSTRAINT fk_messages_sender FOREIGN KEY (sender_id) REFERENCES users (user_id),
    CONSTRAINT ck_messages_type CHECK (message_type IN ('TEXT', 'IMAGE', 'SYSTEM')),
    CONSTRAINT ck_messages_content_not_blank CHECK (length(btrim(content)) > 0),
    CONSTRAINT ck_messages_read_time CHECK (read_at IS NULL OR read_at >= created_at)
);

CREATE INDEX ix_messages_conversation_created ON messages (conversation_id, created_at, message_id);
CREATE INDEX ix_messages_sender_id ON messages (sender_id);

CREATE TABLE offers (
    offer_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id       BIGINT NOT NULL,
    buyer_id         BIGINT NOT NULL,
    seller_id        BIGINT NOT NULL,
    offer_price      NUMERIC(19,2) NOT NULL,
    status           VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    expires_at       TIMESTAMPTZ,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    responded_at     TIMESTAMPTZ,

    CONSTRAINT fk_offers_product FOREIGN KEY (product_id) REFERENCES products (product_id),
    CONSTRAINT fk_offers_buyer FOREIGN KEY (buyer_id) REFERENCES users (user_id),
    CONSTRAINT fk_offers_seller FOREIGN KEY (seller_id) REFERENCES users (user_id),
    CONSTRAINT ck_offers_distinct_users CHECK (buyer_id <> seller_id),
    CONSTRAINT ck_offers_price CHECK (offer_price > 0),
    CONSTRAINT ck_offers_status CHECK (status IN ('PENDING', 'ACCEPTED', 'REJECTED', 'COUNTERED', 'EXPIRED')),
    CONSTRAINT ck_offers_response CHECK (
        (status = 'PENDING' AND responded_at IS NULL)
        OR
        (status <> 'PENDING' AND responded_at IS NOT NULL)
    ),
    CONSTRAINT ck_offers_expiry CHECK (expires_at IS NULL OR expires_at > created_at)
);

CREATE INDEX ix_offers_product_status ON offers (product_id, status, created_at DESC);
CREATE INDEX ix_offers_buyer_status ON offers (buyer_id, status, created_at DESC);
CREATE INDEX ix_offers_seller_status ON offers (seller_id, status, created_at DESC);
CREATE UNIQUE INDEX uq_offers_one_pending_per_buyer_product
    ON offers (product_id, buyer_id)
    WHERE status = 'PENDING';

