-- Trust-oriented Second-hand C2C Marketplace (O.G Shop)
-- Baseline Flyway Migration V1: Core Tables, pgvector & eKYC Biometrics

CREATE EXTENSION IF NOT EXISTS vector;

-- ============================================================================
-- 1. Identity & Access Management
-- ============================================================================

CREATE TABLE users (
    user_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email           VARCHAR(320) NOT NULL,
    password_hash   VARCHAR(255) NOT NULL,
    full_name       VARCHAR(120) NOT NULL,
    phone_number    VARCHAR(20),
    avatar_url      TEXT,
    status          VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    created_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMPTZ,
    deleted_at      TIMESTAMPTZ,

    CONSTRAINT ck_users_email_normalized CHECK (email = lower(btrim(email))),
    CONSTRAINT ck_users_status CHECK (status IN ('ACTIVE', 'SUSPENDED', 'LOCKED', 'DEACTIVATED')),
    CONSTRAINT ck_users_deleted_state CHECK (deleted_at IS NULL OR status = 'DEACTIVATED')
);

CREATE UNIQUE INDEX uq_users_email ON users (email);
CREATE UNIQUE INDEX uq_users_phone_number ON users (phone_number) WHERE phone_number IS NOT NULL;

CREATE TABLE roles (
    role_id         SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_name       VARCHAR(20) NOT NULL UNIQUE,
    description     VARCHAR(255),

    CONSTRAINT ck_roles_name CHECK (role_name IN ('BUYER', 'SELLER', 'ADMIN'))
);

CREATE TABLE user_roles (
    user_id         BIGINT NOT NULL,
    role_id         SMALLINT NOT NULL,
    granted_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    granted_by      BIGINT,

    CONSTRAINT pk_user_roles PRIMARY KEY (user_id, role_id),
    CONSTRAINT fk_user_roles_user FOREIGN KEY (user_id) REFERENCES users (user_id),
    CONSTRAINT fk_user_roles_role FOREIGN KEY (role_id) REFERENCES roles (role_id),
    CONSTRAINT fk_user_roles_granted_by FOREIGN KEY (granted_by) REFERENCES users (user_id)
);

CREATE INDEX ix_user_roles_role_id ON user_roles (role_id);
CREATE INDEX ix_user_roles_granted_by ON user_roles (granted_by) WHERE granted_by IS NOT NULL;

CREATE TABLE addresses (
    address_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT NOT NULL,
    recipient_name  VARCHAR(120) NOT NULL,
    phone_number    VARCHAR(20) NOT NULL,
    province        VARCHAR(100) NOT NULL,
    district        VARCHAR(100) NOT NULL,
    ward            VARCHAR(100) NOT NULL,
    detail_address  VARCHAR(255) NOT NULL,
    is_default      BOOLEAN NOT NULL DEFAULT FALSE,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMPTZ,
    deleted_at      TIMESTAMPTZ,

    CONSTRAINT fk_addresses_user FOREIGN KEY (user_id) REFERENCES users (user_id)
);

CREATE INDEX ix_addresses_user_id ON addresses (user_id);
CREATE UNIQUE INDEX uq_addresses_one_default_per_user
    ON addresses (user_id)
    WHERE is_default = TRUE AND deleted_at IS NULL;

-- ============================================================================
-- 2. Seller Verification & Biometric eKYC
-- ============================================================================

CREATE TABLE seller_verifications (
    verification_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id               BIGINT NOT NULL,
    verification_method   VARCHAR(30) NOT NULL DEFAULT 'MANUAL_ID_DOCUMENT',
    status                VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    document_data         JSONB NOT NULL DEFAULT '{}'::jsonb,
    rejection_reason      VARCHAR(500),
    submitted_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    reviewed_at           TIMESTAMPTZ,
    verified_by           BIGINT,

    CONSTRAINT fk_seller_verifications_user FOREIGN KEY (user_id) REFERENCES users (user_id),
    CONSTRAINT fk_seller_verifications_admin FOREIGN KEY (verified_by) REFERENCES users (user_id),
    CONSTRAINT ck_seller_verifications_method CHECK (verification_method IN ('MANUAL_ID_DOCUMENT', 'AI_EKYC')),
    CONSTRAINT ck_seller_verifications_status CHECK (status IN ('PENDING', 'VERIFIED', 'REJECTED')),
    CONSTRAINT ck_seller_verifications_document_object CHECK (jsonb_typeof(document_data) = 'object'),
    CONSTRAINT ck_seller_verifications_resolution CHECK (
        (status = 'PENDING' AND reviewed_at IS NULL AND verified_by IS NULL AND rejection_reason IS NULL)
        OR
        (status = 'VERIFIED' AND reviewed_at IS NOT NULL AND verified_by IS NOT NULL AND rejection_reason IS NULL)
        OR
        (status = 'REJECTED' AND reviewed_at IS NOT NULL AND verified_by IS NOT NULL AND rejection_reason IS NOT NULL)
    )
);

CREATE INDEX ix_seller_verifications_user_id ON seller_verifications (user_id);
CREATE INDEX ix_seller_verifications_verified_by ON seller_verifications (verified_by) WHERE verified_by IS NOT NULL;
CREATE INDEX ix_seller_verifications_status_submitted ON seller_verifications (status, submitted_at);
CREATE UNIQUE INDEX uq_seller_verifications_one_open_or_verified
    ON seller_verifications (user_id)
    WHERE status IN ('PENDING', 'VERIFIED');

CREATE TABLE seller_biometrics (
    biometric_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT NOT NULL,
    verification_id     BIGINT NOT NULL,
    cccd_number         VARCHAR(20) NOT NULL,
    full_name           VARCHAR(120) NOT NULL,
    dob                 VARCHAR(20),
    hometown            TEXT,
    address             TEXT,
    face_embedding      vector(512) NOT NULL,
    match_distance      NUMERIC(5,4),
    card_front_url      TEXT,
    selfie_photo_url    TEXT,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_seller_biometrics_user FOREIGN KEY (user_id) REFERENCES users (user_id),
    CONSTRAINT fk_seller_biometrics_verification FOREIGN KEY (verification_id) REFERENCES seller_verifications (verification_id) ON DELETE CASCADE,
    CONSTRAINT uq_seller_biometrics_user UNIQUE (user_id),
    CONSTRAINT uq_seller_biometrics_cccd UNIQUE (cccd_number)
);

CREATE INDEX ix_seller_biometrics_user_id ON seller_biometrics (user_id);
CREATE INDEX ix_seller_biometrics_cccd ON seller_biometrics (cccd_number);
CREATE INDEX ix_seller_biometrics_embedding ON seller_biometrics USING ivfflat (face_embedding vector_cosine_ops) WITH (lists = 100);

-- ============================================================================
-- 3. Catalog & Products
-- ============================================================================

CREATE TABLE categories (
    category_id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_category_id     BIGINT,
    category_name          VARCHAR(100) NOT NULL,
    slug                   VARCHAR(120) NOT NULL UNIQUE,
    description            VARCHAR(500),
    is_active              BOOLEAN NOT NULL DEFAULT TRUE,
    display_order          INTEGER NOT NULL DEFAULT 0,
    created_at             TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at             TIMESTAMPTZ,

    CONSTRAINT fk_categories_parent FOREIGN KEY (parent_category_id) REFERENCES categories (category_id),
    CONSTRAINT ck_categories_not_self_parent CHECK (parent_category_id IS NULL OR parent_category_id <> category_id),
    CONSTRAINT ck_categories_display_order CHECK (display_order >= 0),
    CONSTRAINT uq_categories_sibling_name UNIQUE NULLS NOT DISTINCT (parent_category_id, category_name)
);

CREATE INDEX ix_categories_parent_id ON categories (parent_category_id) WHERE parent_category_id IS NOT NULL;

CREATE TABLE products (
    product_id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seller_id               BIGINT NOT NULL,
    category_id             BIGINT NOT NULL,
    title                   VARCHAR(200) NOT NULL,
    description             TEXT NOT NULL,
    price                   NUMERIC(19,2) NOT NULL,
    currency                CHAR(3) NOT NULL DEFAULT 'VND',
    condition               VARCHAR(20) NOT NULL,
    usage_duration          VARCHAR(100),
    defects                 TEXT,
    repair_history          TEXT,
    included_accessories    TEXT,
    location                VARCHAR(255),
    status                  VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    reserved_until          TIMESTAMPTZ,
    reserved_order_id       BIGINT,
    version                 BIGINT NOT NULL DEFAULT 0,
    created_at              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at              TIMESTAMPTZ,
    deleted_at              TIMESTAMPTZ,

    CONSTRAINT fk_products_seller FOREIGN KEY (seller_id) REFERENCES users (user_id),
    CONSTRAINT fk_products_category FOREIGN KEY (category_id) REFERENCES categories (category_id),
    CONSTRAINT ck_products_price CHECK (price > 0),
    CONSTRAINT ck_products_currency CHECK (currency = 'VND'),
    CONSTRAINT ck_products_condition CHECK (condition IN ('LIKE_NEW', 'GOOD', 'FAIR', 'POOR', 'FOR_PARTS')),
    CONSTRAINT ck_products_status CHECK (status IN ('DRAFT', 'PENDING', 'ACTIVE', 'RESERVED', 'SOLD', 'HIDDEN', 'REJECTED')),
    CONSTRAINT ck_products_reservation CHECK (
        (status = 'RESERVED' AND reserved_until IS NOT NULL AND reserved_order_id IS NOT NULL)
        OR
        (status <> 'RESERVED' AND reserved_until IS NULL AND reserved_order_id IS NULL)
    ),
    CONSTRAINT ck_products_deleted_state CHECK (deleted_at IS NULL OR status IN ('HIDDEN', 'SOLD'))
);

CREATE INDEX ix_products_seller_status ON products (seller_id, status) WHERE deleted_at IS NULL;
CREATE INDEX ix_products_category_status_created ON products (category_id, status, created_at DESC) WHERE deleted_at IS NULL;
CREATE INDEX ix_products_active_created ON products (created_at DESC) WHERE status = 'ACTIVE' AND deleted_at IS NULL;
CREATE INDEX ix_products_reservation_expiry ON products (reserved_until) WHERE status = 'RESERVED';
CREATE INDEX ix_products_reserved_order_id ON products (reserved_order_id) WHERE reserved_order_id IS NOT NULL;
CREATE INDEX ix_products_title_search ON products USING GIN (to_tsvector('simple', title));

CREATE TABLE product_media (
    media_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id      BIGINT NOT NULL,
    media_type      VARCHAR(10) NOT NULL,
    media_url       TEXT NOT NULL,
    display_order   INTEGER NOT NULL DEFAULT 0,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_product_media_product FOREIGN KEY (product_id) REFERENCES products (product_id),
    CONSTRAINT ck_product_media_type CHECK (media_type IN ('IMAGE', 'VIDEO')),
    CONSTRAINT ck_product_media_order CHECK (display_order >= 0),
    CONSTRAINT uq_product_media_order UNIQUE (product_id, display_order)
);

CREATE INDEX ix_product_media_product_id ON product_media (product_id);

